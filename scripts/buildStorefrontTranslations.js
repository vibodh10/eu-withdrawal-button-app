import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { EU_LANGUAGE_CODES } from '../shared/euLanguages.js';

const root = fileURLToPath(new URL('../', import.meta.url));
export const supportedLanguages = EU_LANGUAGE_CODES;
export const errorKeys = {
    'Customer name, email address and order number are required.': 'requiredDetails',
    'Invalid submission details.': 'invalidDetails',
    'Too many withdrawal requests. Please try again later.': 'tooManyRequests',
    'Shop is not installed.': 'shopNotInstalled',
    'The merchant must activate a paid app plan.': 'planRequired',
    'We could not verify the order details provided. Check the order number and email address and try again.': 'orderDetailsUnverified',
    'We could not verify the order date. Please try again later.': 'orderDateUnverified',
    'We could not verify the order. Please try again later.': 'orderUnverified',
    'Temporary server issue. Please try again in a few minutes.': 'temporaryServerIssue',
    'Could not create withdrawal request.': 'createFailed',
    'Unauthorised request': 'unauthorised',
    'Expired request': 'expiredRequest',
    'Store access suspended': 'storeSuspended',
};

export function readTranslations() {
    return Object.fromEntries(supportedLanguages.map((code) => [
        code, JSON.parse(fs.readFileSync(path.join(root, `storefront/withdrawal/locales/${code}.json`), 'utf8')),
    ]));
}

export function validateTranslations(translations) {
    const placeholders = (text) => [...text.matchAll(/\{([^{}]+)\}/g)].map((match) => match[1]).sort();
    const keys = Object.keys(translations.en).sort();
    for (const code of supportedLanguages) {
        const strings = translations[code];
        if (!strings || JSON.stringify(Object.keys(strings).sort()) !== JSON.stringify(keys)) {
            throw new Error(`${code}: translation keys differ from English`);
        }
        for (const key of keys) {
            const value = strings[key];
            if (typeof value !== 'string' || !value.trim()) throw new Error(`${code}.${key}: empty/non-string value`);
            if (/[<>]/.test(value)) throw new Error(`${code}.${key}: translations must be plain text`);
            if (JSON.stringify(placeholders(value)) !== JSON.stringify(placeholders(translations.en[key]))) {
                throw new Error(`${code}.${key}: interpolation placeholders differ`);
            }
        }
    }
}

export function buildAsset(translations = readTranslations()) {
    validateTranslations(translations);
    const runtime = fs.readFileSync(path.join(root, 'storefront/withdrawal/runtime.js'), 'utf8');
    // One self-contained, classic script: no modules, globals, dynamic fetches,
    // or dependence on the order in which Shopify renders the two blocks.
    return '// Generated by node scripts/buildStorefrontTranslations.js. Edit storefront/withdrawal sources.\n'
        + runtime.replace('(function () {', `(function () {\n    const TRANSLATIONS = ${JSON.stringify(translations)};\n    const ERROR_KEYS = ${JSON.stringify(errorKeys)};`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const asset = path.join(root, 'extensions/eu-withdrawal-button/assets/withdrawal-button.js');
    const output = buildAsset();
    if (process.argv.includes('--check')) {
        if (fs.readFileSync(asset, 'utf8') !== output) throw new Error('Storefront asset is stale; run node scripts/buildStorefrontTranslations.js');
    } else fs.writeFileSync(asset, output);
}
